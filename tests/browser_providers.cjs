const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
  assert.equal(process.env.CAMPUSFLOW_ISOLATED_UI, '1', 'Use tests/browser_acceptance.cjs');
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  try{
    await page.goto('http://127.0.0.1:8765');await page.waitForLoadState('networkidle');
    await page.getByRole('button',{name:'打开设置'}).click();
    await page.locator('#modelId').fill('Qwen3.8-27B-GGUF');
    await page.getByRole('button',{name:'保存设置',exact:true}).click();
    await page.locator('#settingsDialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'打开设置'}).click();
    await page.locator('#provider').selectOption('deepseek');
    assert.equal(await page.locator('#baseUrl').inputValue(),'https://api.deepseek.com');
    await page.locator('#modelId').fill('deepseek-flash');
    await page.locator('#apiKey').fill('browser-test-only-key');
    await page.getByRole('button',{name:'保存设置',exact:true}).click();
    await page.locator('#settingsDialog').waitFor({state:'hidden'});
    await page.waitForFunction(()=>document.querySelector('#destinationNotice').textContent.includes('DeepSeek'));
    assert.match(await page.locator('#destinationNotice').innerText(),/发送/);
    await page.reload();await page.waitForLoadState('networkidle');
    await page.getByRole('button',{name:'打开设置'}).click();
    assert.equal(await page.locator('#provider').inputValue(),'deepseek');
    assert.equal(await page.locator('#apiKey').inputValue(),'');
    assert.match(await page.locator('#keyStatus').innerText(),/已有密钥/);
    await page.getByRole('button',{name:'保存设置',exact:true}).click();
    await page.locator('#settingsDialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'打开设置'}).click();
    assert.match(await page.locator('#keyStatus').innerText(),/已有密钥/);
    await page.locator('#clearKey').check();
    await page.getByRole('button',{name:'保存设置',exact:true}).click();
    await page.locator('#settingsDialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'打开设置'}).click();
    assert.equal((await (await fetch('http://127.0.0.1:8765/api/config')).json()).profiles.deepseek.has_api_key,false);
    await page.locator('#provider').selectOption('openai');
    assert.equal(await page.locator('#baseUrl').inputValue(),'https://api.openai.com/v1');
    assert.equal(await page.locator('#apiKey').inputValue(),'');
    await page.locator('#provider').selectOption('local');
    assert.equal(await page.locator('#modelId').inputValue(),'Qwen3.8-27B-GGUF');
    await page.getByRole('button',{name:'保存设置',exact:true}).click();
    await page.locator('#settingsDialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'打开设置'}).click();
    await page.route('**/api/models',route=>route.fulfill({json:{models:['test-text-model']}}));
    await page.locator('#detectModelsBtn').click();
    await page.locator('[data-model="test-text-model"]').waitFor();
    await page.locator('[data-model="test-text-model"]').click();
    assert.equal(await page.locator('#modelId').inputValue(),'test-text-model');
    await page.getByRole('button',{name:'保存设置',exact:true}).click();
    await page.locator('#settingsDialog').waitFor({state:'hidden'});
    await page.unroute('**/api/models');
    assert.deepEqual(errors,[]);
    console.log('Provider UI passed: local/DeepSeek/OpenAI profiles, disclosure, encrypted-key persistence and no key readback. Key retention/clearing and model detection UI (mocked list) passed. No paid API requests sent.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
